const catalog: Readonly<Record<string, string>> = english;
export function translate(language: 'ja' | 'en', text: string): string {
  if (language === 'ja') return text;
  const marker = ' 受付番号: ';
  const boundary = text.indexOf(marker);
  const message = boundary < 0 ? text : text.slice(0, boundary);
  return (
    (catalog[message] ?? message) +
    (boundary < 0 ? '' : ` Request ID: ${text.slice(boundary + marker.length)}`)
  );
}
